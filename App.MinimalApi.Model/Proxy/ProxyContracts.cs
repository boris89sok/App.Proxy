namespace App.MinimalApi.Model.Proxy;

/// <summary>
/// Envelope of <c>POST /api/proxy/execute</c>. Parsed STRICTLY by the proxy: any property other than
/// these is rejected, so a caller can never supply a destination URL, HTTP method, path or headers.
/// <code>
/// { "clientId": "customer.get", "json": { "urlId": 5 } }
/// { "clientId": "customer.secure-get", "encrypted": { "nonce": "..", "ciphertext": "..", "tag": ".." } }
/// </code>
/// </summary>
public sealed class ProxyExecuteRequest
{
    /// <summary>Configured operation key, e.g. <c>customer.get</c>.</summary>
    [JsonPropertyName("clientId")]
    public string ClientId { get; set; } = string.Empty;

    /// <summary>Plain-text parameters object. Must contain <c>urlId</c>.</summary>
    [JsonPropertyName("json")]
    public JsonElement? Json { get; set; }

    /// <summary>AES-256-GCM encrypted parameters object (for operations that require encryption).</summary>
    [JsonPropertyName("encrypted")]
    public EncryptedPayload? Encrypted { get; set; }
}

/// <summary>AES-256-GCM payload. All values are base64. AAD = UTF-8 bytes of <c>clientId</c>.</summary>
public sealed class EncryptedPayload
{
    /// <summary>12 byte nonce.</summary>
    [JsonPropertyName("nonce")]
    public string Nonce { get; set; } = string.Empty;

    [JsonPropertyName("ciphertext")]
    public string Ciphertext { get; set; } = string.Empty;

    /// <summary>16 byte authentication tag.</summary>
    [JsonPropertyName("tag")]
    public string Tag { get; set; } = string.Empty;
}

/// <summary>Public, non-sensitive error codes produced by the proxy itself.</summary>
public enum ProxyErrorCode
{
    InvalidEnvelope,
    UnknownEnvelopeField,
    UnsupportedMediaType,
    RequestTooLarge,
    UnknownOperation,
    OperationDisabled,
    DestinationUnavailable,
    OperationMisconfigured,
    EncryptionRequired,
    InvalidEncryptedPayload,
    InvalidParameters,
    InvalidPathParameter,
    InvalidHeader,
    UpstreamTimeout,
    UpstreamUnavailable,
    UpstreamResponseTooLarge,
    UpstreamError,
    AuditUnavailable,
    ConfigurationConflict,
    NotFound,
    InvalidRequest,
    Forbidden,
    InternalError
}

/// <summary>
/// Error body returned for failures. <see cref="Source"/> distinguishes errors generated by the proxy
/// (<c>proxy</c>) from upstream failures (<c>upstream</c>); the same value is sent in the
/// <c>X-Proxy-Source</c> response header.
/// </summary>
public sealed class ProxyErrorResponse
{
    [JsonPropertyName("code")]
    public string Code { get; set; } = string.Empty;

    [JsonPropertyName("message")]
    public string Message { get; set; } = string.Empty;

    [JsonPropertyName("correlationId")]
    public string CorrelationId { get; set; } = string.Empty;

    [JsonPropertyName("source")]
    public string Source { get; set; } = "proxy";

    [JsonPropertyName("upstreamStatus")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public int? UpstreamStatus { get; set; }

    /// <summary>Field-level validation problems (parameter names only, never values).</summary>
    [JsonPropertyName("errors")]
    [JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)]
    public IReadOnlyList<string>? Errors { get; set; }
}

/// <summary>Operation configuration returned by <c>IProxyConfigAdminService</c> (no secrets).</summary>
public sealed class OperationAdminDto
{
    public int Id { get; set; }
    public string OperationKey { get; set; } = string.Empty;
    public int DestinationId { get; set; }
    public string HttpMethod { get; set; } = string.Empty;
    public string PathTemplate { get; set; } = string.Empty;
    public bool IsEnabled { get; set; }
    public int MaxRequestBytes { get; set; }
    public int MaxResponseBytes { get; set; }
    public bool AllowUnknownParameters { get; set; }
    public bool RequiresEncryption { get; set; }
    public int? EncryptionProfileId { get; set; }
    public DateTime UpdatedAt { get; set; }
    public string? UpdatedBy { get; set; }
    /// <summary>Base64 SQL Server rowversion - send back unchanged on update (optimistic concurrency).</summary>
    public string RowVersion { get; set; } = string.Empty;
}

/// <summary>Updatable operation fields. HttpMethod / OperationKey / DestinationId are intentionally not updatable here.</summary>
public sealed class OperationUpdateDto
{
    public bool IsEnabled { get; set; }
    public string PathTemplate { get; set; } = string.Empty;
    public int MaxRequestBytes { get; set; }
    public int MaxResponseBytes { get; set; }
    public bool AllowUnknownParameters { get; set; }
}

public sealed class DestinationAdminDto
{
    public int Id { get; set; }
    public string Name { get; set; } = string.Empty;
    public string BaseUrl { get; set; } = string.Empty;
    public bool IsEnabled { get; set; }
    public int TimeoutSeconds { get; set; }
    public string? AllowedPorts { get; set; }
    public DateTime UpdatedAt { get; set; }
    public string? UpdatedBy { get; set; }
    public string RowVersion { get; set; } = string.Empty;
}

public sealed class DestinationUpdateDto
{
    public bool IsEnabled { get; set; }
    public string BaseUrl { get; set; } = string.Empty;
    public int TimeoutSeconds { get; set; }
    public string? AllowedPorts { get; set; }
}
